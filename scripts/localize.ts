/** Explicit development-only catalog generation. Never imported by the panel,
 * Service, check or package. Only authored English UI strings leave this process;
 * no configuration, production data, keys or fetched resource values are read. */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { setTimeout as delay } from 'node:timers/promises';
import { english, chinese } from '../src/shared/locales/base.js';
import { LANGUAGES } from '../src/shared/language.js';

if (!process.argv.includes('--translate-authored-messages')) throw new Error('Explicit --translate-authored-messages is required. Not an automatic build step.');
const scratch = join(tmpdir(), 'opencode', 'argocd-authored-translations-english-keys-v1'); await mkdir(scratch, { recursive: true });
const entries = Object.entries(english);
if (entries.some(([key]) => /\p{Script=Han}/u.test(key))) throw new Error('Translation keys must be authored in English.');
const locales = LANGUAGES.filter((locale) => !['en', 'zh-CN'].includes(locale));
const output: Record<string, Record<string, string>> = {};
async function translate(locale: string, source: string): Promise<string> {
  const url = new URL('https://translate.googleapis.com/translate_a/single');
  url.search = new URLSearchParams({ client: 'gtx', sl: locale === 'zh-TW' ? 'zh-CN' : 'en', tl: locale, dt: 't', q: source }).toString();
  for (let attempt = 0; attempt < 5; attempt++) {
    const response = await fetch(url, { signal: AbortSignal.timeout(45000) });
    if (!response.ok) { await delay(1500 * (attempt + 1)); continue; }
    const body = await response.json() as [Array<[string]>];
    return body[0].map((segment) => segment[0]).join('');
  }
  throw new Error(`Translation transport failed: ${locale}`);
}
for (const locale of locales) {
  const catalog: Record<string, string> = {}; const cacheFile = join(scratch, `${locale}.json`);
  try { Object.assign(catalog, JSON.parse(await readFile(cacheFile, 'utf8'))); } catch { /* first run */ }
  if (process.argv.includes('--refresh-terminology')) for (const [key, text] of entries) if (locale === 'zh-TW' || /composer|redact/i.test(text)) delete catalog[key];
  const sourceText = (key: string, text: string) => locale === 'zh-TW' ? chinese[key] ?? text
    : text.replace(/\bcomposer\b/gi, 'chat input box').replace(/\bredacted\b/gi, 'privacy-filtered').replace(/\bredaction\b/gi, 'removal of sensitive data');
  const pending = entries.filter(([key]) => !catalog[key]);
  // Each marker occupies its own line. Placeholders/newlines are protected and
  // checked before any generated catalog can be committed to the project.
  for (let start = 0; start < pending.length;) {
    const batch: Array<[string, string]> = []; let length = 0;
    while (start < pending.length && length < 2600) { const item = pending[start++]!; batch.push(item); length += item[1].length + 24; }
    const source = batch.map(([key, text], index) => `⟦${String(index).padStart(4, '0')}⟧\n${sourceText(key, text).replace(/\{(\d+)\}/g, '_OCVAR$1_').replace(/\n/g, '_OCNEWLINE_')}`).join('\n\n');
    const translated = await translate(locale, source);
    const segments = [...translated.matchAll(/⟦\s*(\d+)\s*⟧\s*([\s\S]*?)(?=⟦\s*\d+\s*⟧|$)/g)];
    if (segments.length !== batch.length) throw new Error(`Translation marker mismatch: ${locale}`);
    for (const segment of segments) {
      const [key, original] = batch[Number(segment[1])]!;
      let text = segment[2]!.trim().replace(/_\s*OCVAR\s*(\d+)\s*_/gi, '{$1}').replace(/_\s*OCNEWLINE\s*_/gi, '\n');
      const placeholders = (value: string) => [...value.matchAll(/\{\d+\}/g)].map((match) => match[0]).sort().join(',');
      if (placeholders(text) !== placeholders(original) || /OCVAR|OCNEWLINE/.test(text)) {
        // Some translation models merge adjacent marker tokens. Retry the one
        // authored sentence with ordinary, space-separated numbered variables.
        text = (await translate(locale, sourceText(key, original).replace(/\{(\d+)\}/g, ' {$1} '))).trim().replace(/\{\s*(\d+)\s*\}/g, '{$1}');
      }
      if (placeholders(text) !== placeholders(original) || /OCVAR|OCNEWLINE/.test(text)) throw new Error(`Translation placeholder mismatch: ${locale}/${key}`);
      catalog[key] = (original.match(/^\s+/)?.[0] ?? '') + text + (original.match(/\s+$/)?.[0] ?? '');
    }
    await writeFile(cacheFile, JSON.stringify(catalog, null, 2)); await delay(150);
  }
  if (entries.some(([key]) => !catalog[key])) throw new Error(`Incomplete locale: ${locale}`);
  output[locale] = Object.fromEntries(entries.map(([key]) => [key, catalog[key]!])); console.log(`Catalog complete: ${locale} (${entries.length} messages)`);
}
await writeFile('src/shared/locales/generated.ts', `/** Bundled machine-translated authored messages; no runtime translation calls.\n * Generated by scripts/localize.ts; preserve numbered placeholders. */\nimport type { Language } from '../language.js';\nexport const translations: Record<Exclude<Language, 'en' | 'zh-CN'>, Record<string, string>> = ${JSON.stringify(output, null, 2)};\n`);
